"""Durable discovery and ingestion job orchestration.

Flow (all steps idempotent, safe under retries and concurrent workers):

    plan topics (CSE taxonomy, fewest cards first)
      -> lease a SourceDiscoveryCheckpoint, call adapter.discover(), save cursor
      -> upsert one IngestionJob per provider record (unique adapter+external_id)
      -> on commit: enqueue knowledge.process_ingestion_job
      -> claim job (conditional UPDATE), fetch, ExternalIngestionPipeline.ingest_item()
      -> verification creates CanonicalClaims; flashcards are generated by
         learning.generate_flashcard_for_claim after commit.

Recovery: ``recover_stale_jobs`` re-enqueues jobs whose dispatch was lost,
whose worker died mid-processing (expired lease), or whose retry is due.
"""
import logging
import random
from dataclasses import dataclass, field
from datetime import timedelta

from django.conf import settings
from django.db import IntegrityError, transaction
from django.db.models import Count, F, Q
from django.utils import timezone

from knowledge.ingestion.http import PermanentProviderError, RateLimitedError, TransientProviderError
from knowledge.ingestion.license_checker import LicensePolicyError
from knowledge.ingestion.pipeline import ExternalIngestionPipeline, InsufficientContentError
from knowledge.ingestion.registry import get_adapter, policy_key_for, topic_enabled
from knowledge.models import Concept, IngestionJob, SourceDiscoveryCheckpoint

logger = logging.getLogger(__name__)

ROOT_CONCEPT_SLUG = "cse"


def _setting(name, default):
    return getattr(settings, name, default)


def per_adapter_limit(adapter_name: str) -> int:
    limits = _setting("INGESTION_MAX_CANDIDATES_PER_RUN", {}) or {}
    return int(limits.get(adapter_name, _setting("INGESTION_DEFAULT_MAX_CANDIDATES_PER_RUN", 5)))


def backoff_seconds(attempt: int, *, base: float = 60.0, cap: float = 3600.0) -> float:
    """Bounded exponential backoff with full jitter on top of the base delay."""
    delay = min(base * (2 ** max(attempt - 1, 0)), cap)
    return delay + random.uniform(0, delay / 2)


class TopicPlanner:
    """Chooses CSE taxonomy topics that most need flashcards."""

    @staticmethod
    def concepts_needing_cards(limit: int) -> list[Concept]:
        # Lowest active-card coverage first; random order among ties so runs
        # spread across the taxonomy instead of retrying the same concepts.
        return list(
            Concept.objects.exclude(slug=ROOT_CONCEPT_SLUG)
            .annotate(
                card_count=Count(
                    "canonical_claims__flashcards",
                    filter=Q(canonical_claims__flashcards__is_active=True),
                    distinct=True,
                )
            )
            .order_by("card_count", "?")[:limit]
        )

    @classmethod
    def topics_for(cls, adapter, limit: int) -> list[tuple[str, str, Concept | None]]:
        """Return [(topic_key, topic, concept)] for one discovery run."""
        fixed = getattr(type(adapter), "fixed_topics", None)
        if callable(fixed):
            topics = [key for key in fixed() if topic_enabled(adapter.name, key)]
            return [(key, key, None) for key in topics][:limit]
        return [(f"concept:{concept.id}", concept.name, concept) for concept in cls.concepts_needing_cards(limit)]


@dataclass
class DiscoveryStats:
    adapter: str
    topics: int = 0
    candidates: int = 0
    jobs_created: int = 0
    jobs_requeued: int = 0
    skipped_topics: int = 0
    errors: list[str] = field(default_factory=list)

    def as_dict(self) -> dict:
        return self.__dict__.copy()


class DiscoveryService:
    LEASE = timedelta(minutes=10)

    def __init__(self, adapter_name: str):
        self.adapter = get_adapter(adapter_name)
        self.adapter_name = self.adapter.name

    def run(self, *, max_topics: int | None = None, limit: int | None = None, topic: str | None = None,
            enqueue: bool = True) -> DiscoveryStats:
        stats = DiscoveryStats(adapter=self.adapter_name)
        limit = limit or per_adapter_limit(self.adapter_name)
        max_topics = max_topics or int(_setting("INGESTION_TOPICS_PER_RUN", 3))
        if topic:
            topics = [(f"manual:{topic.lower()}", topic, None)]
        else:
            topics = TopicPlanner.topics_for(self.adapter, max_topics)
        remaining = limit
        for topic_key, topic_name, concept in topics:
            if remaining <= 0:
                break
            checkpoint = self._lease_checkpoint(topic_key, topic_name, concept)
            if checkpoint is None:
                stats.skipped_topics += 1
                continue
            stats.topics += 1
            try:
                page = self.adapter.discover(topic_name, cursor=checkpoint.cursor or None, limit=remaining)
            except (TransientProviderError, PermanentProviderError, ValueError) as exc:
                self._release(checkpoint, error=exc)
                stats.errors.append(f"{topic_name}: {exc}")
                logger.warning("ingestion.discovery.failed adapter=%s topic=%s error=%s", self.adapter_name, topic_name, exc)
                if isinstance(exc, RateLimitedError):
                    break
                continue
            created, requeued = self._upsert_jobs(page.candidates, topic_name, concept, enqueue=enqueue)
            stats.candidates += len(page.candidates)
            stats.jobs_created += created
            stats.jobs_requeued += requeued
            remaining -= created + requeued
            self._release(checkpoint, page=page)
        logger.info("ingestion.discovery.completed %s", stats.as_dict())
        return stats

    def _lease_checkpoint(self, topic_key, topic_name, concept) -> SourceDiscoveryCheckpoint | None:
        now = timezone.now()
        try:
            checkpoint, _ = SourceDiscoveryCheckpoint.objects.get_or_create(
                adapter=self.adapter_name, topic_key=topic_key,
                defaults={"topic": topic_name[:255], "concept": concept},
            )
        except IntegrityError:
            checkpoint = SourceDiscoveryCheckpoint.objects.get(adapter=self.adapter_name, topic_key=topic_key)
        if checkpoint.next_run_at and checkpoint.next_run_at > now:
            return None
        # Atomic lease: only one worker pages a given query at a time.
        leased = SourceDiscoveryCheckpoint.objects.filter(pk=checkpoint.pk).filter(
            Q(lease_until__isnull=True) | Q(lease_until__lt=now)
        ).update(lease_until=now + self.LEASE, last_run_at=now, runs=F("runs") + 1)
        if not leased:
            return None
        checkpoint.refresh_from_db()
        if checkpoint.exhausted:
            # Restart exhausted queries after the revisit window so updated content is found.
            checkpoint.cursor = {}
            checkpoint.exhausted = False
        return checkpoint

    def _release(self, checkpoint, *, page=None, error=None) -> None:
        now = timezone.now()
        checkpoint.lease_until = None
        if error is not None:
            checkpoint.consecutive_failures += 1
            checkpoint.last_error = str(error)[:2000]
            retry_after = getattr(error, "retry_after", None) or backoff_seconds(checkpoint.consecutive_failures, base=300)
            checkpoint.next_run_at = now + timedelta(seconds=retry_after)
        else:
            checkpoint.consecutive_failures = 0
            checkpoint.last_error = ""
            checkpoint.last_success_at = now
            checkpoint.last_candidates = len(page.candidates)
            checkpoint.candidates_total += len(page.candidates)
            if page.next_cursor is None:
                checkpoint.exhausted = True
                checkpoint.cursor = {}
                checkpoint.next_run_at = now + timedelta(days=int(_setting("INGESTION_REVISIT_DAYS", 7)))
            else:
                checkpoint.cursor = page.next_cursor
                checkpoint.next_run_at = None
        checkpoint.save()

    def _upsert_jobs(self, candidates, topic_name, concept, *, enqueue: bool) -> tuple[int, int]:
        created = requeued = 0
        refresh_before = timezone.now() - timedelta(days=int(_setting("INGESTION_REVISIT_DAYS", 7)))
        to_enqueue = []
        with transaction.atomic():
            for candidate in candidates:
                job, was_created = IngestionJob.objects.get_or_create(
                    adapter=self.adapter_name,
                    external_id=candidate.external_id[:255],
                    defaults={
                        "identifier": candidate.identifier[:512],
                        "fetch_kwargs": candidate.fetch_kwargs,
                        "title": candidate.title[:255],
                        "url": candidate.url[:1000],
                        "topic": topic_name[:255],
                        "topic_concept": concept,
                        "max_attempts": int(_setting("INGESTION_MAX_ATTEMPTS", 4)),
                    },
                )
                if was_created:
                    created += 1
                    to_enqueue.append(job.id)
                elif job.status in (IngestionJob.STATUS_SUCCEEDED, IngestionJob.STATUS_UNCHANGED) and (
                    job.completed_at is None or job.completed_at < refresh_before
                ):
                    # Revisit to detect content changes; unchanged content is deduplicated by hash.
                    updated = IngestionJob.objects.filter(pk=job.pk, status=job.status).update(
                        status=IngestionJob.STATUS_PENDING, attempts=0, last_error="", next_attempt_at=None,
                    )
                    if updated:
                        requeued += 1
                        to_enqueue.append(job.id)
            if enqueue and to_enqueue:
                transaction.on_commit(lambda ids=tuple(to_enqueue): enqueue_jobs(ids))
        return created, requeued


def enqueue_jobs(job_ids) -> None:
    from knowledge.tasks import process_ingestion_job_task
    now = timezone.now()
    IngestionJob.objects.filter(id__in=job_ids).update(enqueued_at=now)
    for job_id in job_ids:
        process_ingestion_job_task.delay(job_id)


class JobRetry(Exception):
    def __init__(self, countdown: float):
        super().__init__(f"retry in {countdown:.0f}s")
        self.countdown = countdown


class IngestionJobService:
    LEASE = timedelta(minutes=15)

    def __init__(self, pipeline: ExternalIngestionPipeline | None = None):
        self._pipeline = pipeline

    @property
    def pipeline(self) -> ExternalIngestionPipeline:
        if self._pipeline is None:
            self._pipeline = ExternalIngestionPipeline()
        return self._pipeline

    def claim(self, job_id: int) -> IngestionJob | None:
        now = timezone.now()
        claimed = IngestionJob.objects.filter(
            pk=job_id, status__in=IngestionJob.CLAIMABLE_STATUSES,
        ).filter(Q(locked_until__isnull=True) | Q(locked_until__lt=now)).update(
            status=IngestionJob.STATUS_PROCESSING,
            attempts=F("attempts") + 1,
            locked_until=now + self.LEASE,
            started_at=now,
        )
        return IngestionJob.objects.get(pk=job_id) if claimed else None

    def process(self, job_id: int) -> IngestionJob | None:
        """Process one job. Raises JobRetry when a transient failure should be retried."""
        job = self.claim(job_id)
        if job is None:
            return None  # Already processed, in progress elsewhere, or not due.

        try:
            if not topic_enabled(job.adapter, job.identifier if job.adapter == "official_docs" else ""):
                raise LicensePolicyError(f"Source policy '{policy_key_for(job.adapter, job.identifier)}' is not enabled.")
            adapter = get_adapter(job.adapter)
            items = adapter.fetch(job.identifier, **(job.fetch_kwargs or {}))
            if not items:
                raise InsufficientContentError("Provider returned no items.")
            summary = self._ingest_items(job, items)
        except LicensePolicyError as exc:
            return self._finish(job, IngestionJob.STATUS_POLICY_REJECTED, error=exc)
        except InsufficientContentError as exc:
            return self._finish(job, IngestionJob.STATUS_SKIPPED, error=exc)
        except PermanentProviderError as exc:
            return self._finish(job, IngestionJob.STATUS_FAILED, error=exc)
        except Exception as exc:  # transient provider errors and unexpected failures
            return self._schedule_retry(job, exc)

        status = IngestionJob.STATUS_UNCHANGED if summary["unchanged"] == summary["items"] else IngestionJob.STATUS_SUCCEEDED
        if summary["items"] and summary["skipped"] == summary["items"]:
            status = IngestionJob.STATUS_SKIPPED
        return self._finish(job, status, result=summary)

    def _ingest_items(self, job: IngestionJob, items) -> dict:
        summary = {
            "items": len(items), "documents_created": 0, "documents_updated": 0, "unchanged": 0,
            "skipped": 0, "evidence_only": 0, "claims_extracted": 0, "claims_supported": 0,
            "canonical_created": 0, "canonical_deduplicated": 0, "flashcards_deferred": 0,
            "document_ids": [], "skip_reasons": [],
        }
        first_document = None
        for item in items:
            try:
                result = self.pipeline.ingest_item(item, defer_flashcards=True, topic_concept_id=job.topic_concept_id)
            except InsufficientContentError as exc:
                if len(items) == 1:
                    raise
                summary["skipped"] += 1
                summary["skip_reasons"].append(str(exc)[:200])
                continue
            document = result["document"]
            first_document = first_document or document
            summary["document_ids"].append(document.id)
            mode = result["mode"]
            if mode == "already_ingested":
                summary["unchanged"] += 1
                continue
            if result.get("document_version") == "updated":
                summary["documents_updated"] += 1
            elif result.get("document_version") == "new":
                summary["documents_created"] += 1
            if mode == "evidence_only":
                summary["evidence_only"] += 1
            summary["claims_extracted"] += len(result.get("claims", []))
            for verification in result.get("verification_results", []):
                if not isinstance(verification, dict):
                    continue
                if verification.get("canonical_claim") is not None:
                    summary["claims_supported"] += 1
                    if verification.get("canonical_created"):
                        summary["canonical_created"] += 1
                    else:
                        summary["canonical_deduplicated"] += 1
                if verification.get("flashcard_deferred"):
                    summary["flashcards_deferred"] += 1
        if first_document is not None:
            job.source_document = first_document
        return summary

    def _finish(self, job: IngestionJob, status: str, *, error=None, result=None) -> IngestionJob:
        job.status = status
        job.locked_until = None
        job.next_attempt_at = None
        job.completed_at = timezone.now()
        job.last_error = f"{type(error).__name__}: {error}"[:2000] if error is not None else ""
        if result is not None:
            job.result = result
        job.save(update_fields=["status", "locked_until", "next_attempt_at", "completed_at", "last_error",
                                "result", "source_document", "updated_at"])
        log = logger.warning if status in (IngestionJob.STATUS_FAILED, IngestionJob.STATUS_POLICY_REJECTED) else logger.info
        log("ingestion.job.finished job=%s adapter=%s status=%s error=%s result=%s",
            job.id, job.adapter, status, job.last_error[:200], {k: v for k, v in (result or {}).items() if k != "document_ids"})
        return job

    def _schedule_retry(self, job: IngestionJob, exc: Exception) -> IngestionJob:
        if job.attempts >= job.max_attempts:
            return self._finish(job, IngestionJob.STATUS_FAILED, error=exc)
        countdown = getattr(exc, "retry_after", None) or backoff_seconds(job.attempts)
        job.status = IngestionJob.STATUS_RETRY
        job.locked_until = None
        job.next_attempt_at = timezone.now() + timedelta(seconds=countdown)
        job.last_error = f"{type(exc).__name__}: {exc}"[:2000]
        job.save(update_fields=["status", "locked_until", "next_attempt_at", "last_error", "updated_at"])
        level = logging.INFO if isinstance(exc, TransientProviderError) else logging.WARNING
        logger.log(level, "ingestion.job.retry job=%s adapter=%s attempt=%s/%s countdown=%.0f error=%s",
                   job.id, job.adapter, job.attempts, job.max_attempts, countdown, job.last_error[:200],
                   exc_info=not isinstance(exc, TransientProviderError))
        raise JobRetry(countdown)


def recover_stale_jobs(limit: int = 200) -> dict:
    """Re-enqueue jobs lost to dispatch failures, worker crashes, or missed retries."""
    now = timezone.now()
    lost_dispatch_before = now - timedelta(minutes=int(_setting("INGESTION_REQUEUE_PENDING_MINUTES", 30)))
    expired = list(
        IngestionJob.objects.filter(status=IngestionJob.STATUS_PROCESSING, locked_until__lt=now)
        .values_list("id", flat=True)[:limit]
    )
    if expired:
        IngestionJob.objects.filter(id__in=expired, status=IngestionJob.STATUS_PROCESSING, locked_until__lt=now).update(
            status=IngestionJob.STATUS_RETRY, locked_until=None, next_attempt_at=now,
            last_error="Worker lease expired (worker restarted or crashed).",
        )
    due = list(
        IngestionJob.objects.filter(
            Q(status=IngestionJob.STATUS_RETRY, next_attempt_at__lte=now)
            | Q(status=IngestionJob.STATUS_PENDING)
            & (Q(enqueued_at__isnull=True, discovered_at__lt=lost_dispatch_before) | Q(enqueued_at__lt=lost_dispatch_before))
        )
        .order_by("discovered_at")
        .values_list("id", flat=True)[:limit]
    )
    # Exhausted retries (worker died on the last attempt) become permanent failures.
    over_limit = IngestionJob.objects.filter(id__in=due, attempts__gte=F("max_attempts"))
    failed = over_limit.update(status=IngestionJob.STATUS_FAILED, completed_at=now)
    due = list(IngestionJob.objects.filter(id__in=due).exclude(status=IngestionJob.STATUS_FAILED).values_list("id", flat=True))
    if due:
        enqueue_jobs(due)
    result = {"expired_leases": len(expired), "requeued": len(due), "failed_over_limit": failed}
    if any(result.values()):
        logger.info("ingestion.recovery %s", result)
    return result
